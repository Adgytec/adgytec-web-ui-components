/**
 * Visual styling variant for text fields and select triggers.
 *
 * - `filled`: Renders a solid container background (default).
 * - `outlined`: Renders a bordered container with a transparent background.
 */
export type FieldVariant = "filled" | "outlined";

/**
 * Alias for {@link FieldVariant} for backwards compatibility.
 */
export type InputVariant = FieldVariant;
